def marker_path(env_dir: str) -> str:
    """Where the unproved marker lives for an environment (base's ``env_dir`` is ``cache/``)."""
    return os.path.join(env_dir, MARKER_NAME)


def read_marker(env_dir: str) -> dict[str, str]:
    """``{family: flavour}`` for families whose probe did not pass, or ``{}``.

    Consulted **before** the drift and ``*.dist-info`` gates, because those gates are exactly
    what would hide it: an environment measured and found broken has a matching hash and every
    member already at ``V``, so the next start would skip the ordered passes and never re-probe.
    A measured-bad environment would go silently into service on the second attempt.
    """
    found: dict[str, str] = {}
    try:
        with open(marker_path(env_dir), 'r', encoding='utf-8') as fh:
            for line in fh:
                name, _, flavour = line.strip().partition(':')
                if name:
                    found[name] = flavour or UNPROVED_FAILED
    except OSError:
        return {}
    return found


def write_marker(env_dir: str, entries: dict[str, str]) -> None:
    """Record (or clear) the families whose probe did not pass.

    Deliberately **not** part of the drift hash: it is an output of a build, and hashing it
    would rebuild the environment where re-proving it is what is wanted.
    """
    path = marker_path(env_dir)
    if not entries:
        try:
            os.remove(path)
        except OSError:
            pass
        return
    os.makedirs(env_dir, exist_ok=True)
    body = ''.join(f'{name}:{flavour}\n' for name, flavour in sorted(entries.items()))
    temporary = f'{path}.{os.getpid()}.tmp'
    with open(temporary, 'w', encoding='utf-8') as fh:
        fh.write(body)
    os.replace(temporary, path)


def update_marker(env_dir: str, family_name: str, flavour: Optional[str]) -> None:
    """Set or clear one family's entry, leaving the others alone.

    Per family rather than per environment: two families can be present, and a passing probe
    must not clear the record of the one that failed beside it.
    """
    entries = read_marker(env_dir)
    if flavour is None:
        entries.pop(family_name, None)
    else:
        entries[family_name] = flavour
    write_marker(env_dir, entries)
